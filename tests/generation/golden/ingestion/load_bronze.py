#!/usr/bin/env python3
"""Ingestion for the `customer_orders` medallion data product (DuckDB).

Generated by dsl-medallion.

Loads each declared CSV source into the layer that declares it under `load`.
Apply `schema/ddl.sql` first: this script inserts into tables, it does not create
them, and exits non-zero with a clear message if a table is missing.

Scope: the regular case only. Re-running appends; there is no de-duplication, no
incremental watermark and no schema-drift handling. Those are data-loading
policy, not scaffolding, and are deliberately left to you.
"""

from __future__ import annotations

import argparse
import pathlib
import sys

import duckdb

#: This script lives at <product>/ingestion/; the database sits at <product>/.
PRODUCT_DIR = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_DATABASE = PRODUCT_DIR / "customer_orders.duckdb"

#: (schema, table, csv glob, columns) for every declared source, in layer order.
LOADS: list[tuple[str, str, str, list[str]]] = [
    (
        "raw",
        "orders",
        "data/raw/orders/*.csv",
        ["order_id", "customer_id", "amount"],
    ),
]


def load(connection, schema: str, table: str, pattern: str, columns: list[str]) -> int:
    """Append one CSV source into its table, binding columns by name."""
    selected = ", ".join(f'"{column}"' for column in columns)
    connection.execute(
        f'INSERT INTO "{schema}"."{table}" ({selected}) '
        f"SELECT {selected} FROM read_csv_auto(?, header = true)",
        [pattern],
    )
    return connection.execute(f'SELECT count(*) FROM "{schema}"."{table}"').fetchone()[0]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--database",
        type=pathlib.Path,
        default=DEFAULT_DATABASE,
        help="DuckDB database to load into (default: %(default)s)",
    )
    parser.add_argument(
        "--source-root",
        type=pathlib.Path,
        default=pathlib.Path.cwd(),
        help=(
            "directory the source paths are relative to; they are taken verbatim "
            "from the specification (default: the current directory)"
        ),
    )
    args = parser.parse_args(argv)

    connection = duckdb.connect(str(args.database))
    try:
        for schema, table, pattern, columns in LOADS:
            resolved = str(args.source_root / pattern)
            try:
                total = load(connection, schema, table, resolved, columns)
            except duckdb.CatalogException as exc:
                print(
                    f'error: table "{schema}"."{table}" does not exist in {args.database}.\n'
                    f"       Apply schema/ddl.sql to this database first.\n"
                    f"       ({exc})",
                    file=sys.stderr,
                )
                return 1
            except duckdb.IOException as exc:
                print(f"error: could not read {resolved}: {exc}", file=sys.stderr)
                return 1
            print(f'loaded "{schema}"."{table}" from {resolved} ({total} row(s) total)')
    finally:
        connection.close()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
