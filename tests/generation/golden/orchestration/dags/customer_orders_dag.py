from __future__ import annotations

import datetime
import os
import pathlib

from airflow.providers.standard.operators.bash import BashOperator
from airflow.sdk import DAG

# This file lives at <product>/orchestration/dags/.
PRODUCT_DIR = pathlib.Path(__file__).resolve().parents[2]
DBT_PROJECT_DIR = PRODUCT_DIR / "dbt"
INGESTION_SCRIPT = PRODUCT_DIR / "ingestion" / "load_bronze.py"

# Source paths are taken verbatim from the specification, so they are relative to
# wherever the raw data is deployed. Set MEDALLION_SOURCE_ROOT on the worker; it
# defaults to the product directory.
SOURCE_ROOT = os.environ.get("MEDALLION_SOURCE_ROOT", str(PRODUCT_DIR))

with DAG(
    dag_id="customer_orders",
    description="Medallion pipeline for customer_orders",
    schedule="0 6 * * *",
    start_date=datetime.datetime(2024, 1, 1),
    catchup=False,
    tags=["medallion", "generated"],
) as dag:
    task_run_ingestion = BashOperator(
        task_id="run_ingestion",
        bash_command=f"python {INGESTION_SCRIPT} --source-root {SOURCE_ROOT}",
    )
    task_bronze = BashOperator(
        task_id="bronze",
        bash_command=f"cd {DBT_PROJECT_DIR} && dbt build --select bronze",
    )
    task_silver = BashOperator(
        task_id="silver",
        bash_command=f"cd {DBT_PROJECT_DIR} && dbt build --select silver",
    )
    task_gold = BashOperator(
        task_id="gold",
        bash_command=f"cd {DBT_PROJECT_DIR} && dbt build --select gold",
    )

    task_run_ingestion >> task_bronze
    task_bronze >> task_silver
    task_silver >> task_gold
